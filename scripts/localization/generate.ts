import { android, formatted, json, resourceId, xml, xmlFile } from "./formats.ts";
import { categories, platforms } from "./schema.ts";
import type { Catalog, Language, Platform, Translations, Value } from "./schema.ts";
import { gettext } from "./gettext.ts";
export function generate(catalog: Catalog, translations: Translations): Record<string, string> {
  const outputs: Record<string, string> = {};
  const ids = Object.keys(catalog.messages).sort();
  const resolved = (platform: Platform, language: Language, id: string): Value => {
    const result =
      catalog.messages[id]?.overrides?.[platform]?.[language] ?? translations[language][id];
    if (result === undefined) throw Error(`Missing ${id}`);
    return result;
  };
  for (const language of ["en", "uk"] as const) {
    outputs[`web/${language}.json`] = json(
      Object.fromEntries(ids.map((id) => [id, resolved("web", language, id)])),
    );
    const androidRows: string[] = [];
    const windowsRows: string[] = [
      '<resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>',
      '<resheader name="version"><value>2.0</value></resheader>',
      '<resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms</value></resheader>',
      '<resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms</value></resheader>',
    ];
    for (const id of ids) {
      const message = catalog.messages[id]!;
      const av = resolved("android", language, id);
      if (typeof av === "string")
        androidRows.push(
          `  <string name="${resourceId(id)}" formatted="${Object.keys(message.arguments).length > 0}">${android(av, message)}</string>`,
        );
      else
        androidRows.push(
          `  <plurals name="${resourceId(id)}">\n${categories[language].map((category) => `    <item quantity="${category}">${android(av[category]!, message)}</item>`).join("\n")}\n  </plurals>`,
        );
      const wv = resolved("windows", language, id);
      for (const [category, text] of typeof wv === "string"
        ? [["", wv]]
        : Object.entries(wv).sort()) {
        windowsRows.push(
          `  <data name="${resourceId(id)}${category ? `_${category}` : ""}" xml:space="preserve"><value>${xml(formatted(text!, message, "windows"))}</value><comment>${xml(message.context)}</comment></data>`,
        );
      }
    }
    outputs[`android/${language === "en" ? "values" : "values-uk"}/strings.xml`] = xmlFile(
      "resources",
      androidRows,
    );
    outputs[`windows/${language}/Resources.resw`] = xmlFile("root", windowsRows);
    outputs[`linux/${language}.po`] = gettext(
      catalog,
      language,
      (id) => resolved("linux", language, id),
      (id) => resolved("linux", "en", id),
    );
  }
  const strings: Record<string, unknown> = {};
  for (const id of ids) {
    const message = catalog.messages[id]!;
    const localizations: Record<string, unknown> = {};
    for (const language of ["en", "uk"] as const) {
      const value = resolved("apple", language, id);
      const unit = (text: string): unknown => ({
        stringUnit: { state: "translated", value: formatted(text, message, "apple") },
      });
      localizations[language] =
        typeof value === "string"
          ? unit(value)
          : {
              variations: {
                plural: Object.fromEntries(
                  categories[language].map((category) => [category, unit(value[category]!)]),
                ),
              },
            };
    }
    strings[id] = { comment: message.context, extractionState: "manual", localizations };
  }
  outputs["apple/Localizable.xcstrings"] = json({ sourceLanguage: "en", strings, version: "1.0" });
  outputs["web/arguments.ts"] =
    "// Generated by scripts/localization.ts. Do not edit.\nexport interface MessageArguments {\n" +
    ids
      .map(
        (id) =>
          `  ${JSON.stringify(id)}: {${Object.entries(catalog.messages[id]!.arguments)
            .sort()
            .map(([name, type]) => `${name}: ${type === "integer" ? "number" : "string"}`)
            .join("; ")}};`,
      )
      .join("\n") +
    "\n}\n";
  outputs["web/contracts.json"] = json(
    Object.fromEntries(
      ids.map((id) => {
        const message = catalog.messages[id]!;
        return [
          id,
          {
            kind: message.kind,
            arguments: Object.fromEntries(Object.entries(message.arguments).sort()),
            ...(message.selector ? { selector: message.selector } : {}),
          },
        ];
      }),
    ),
  );
  outputs["manifest.json"] = json({
    integerDomain: { minimum: 0, maximum: 2147483647 },
    version: 1,
    platforms,
    messages: Object.fromEntries(
      ids.map((id) => [
        id,
        {
          resourceId: resourceId(id),
          kind: catalog.messages[id]!.kind,
          arguments: Object.entries(catalog.messages[id]!.arguments).sort(),
          selector: catalog.messages[id]!.selector,
        },
      ]),
    ),
  });
  return outputs;
}
