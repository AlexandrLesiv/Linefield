import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const signatures: { name: string; args: string[]; result: string; rust: string }[] = [];
function scalar(type: string): string {
  if (/^(u64|i64)$/.test(type.trim())) return "bigint";
  if (/^(u32|usize|f64|\*const f64|\*const u8|\*mut u8)$/.test(type.trim())) return "number";
  throw Error(`Unsupported export scalar: ${type}`);
}
for (const file of ["text_boundary", "text_queries", "text_read"]) {
  const source = readFileSync(`${root}crates/vector-engine/src/${file}.rs`, "utf8");
  for (const match of source.matchAll(/pub extern "C" fn (\w+)\(([^)]*)\)\s*->\s*([^{]+)\{/g)) {
    const args = match[2]!
      .split(",")
      .map((arg) => arg.trim())
      .filter(Boolean)
      .map((arg) => {
        const [name, type] = arg.split(":");
        return `${name!.trim()}: ${scalar(type!)}`;
      });
    signatures.push({
      name: match[1]!,
      args,
      result: scalar(match[3]!),
      rust: `${match[1]}(${match[2]!.replace(/\s+/g, "")})->${match[3]!.replace(/\s+/g, "")}`,
    });
  }
}
signatures.sort((a, b) => a.name.localeCompare(b.name));
if (signatures.length !== 15 || new Set(signatures.map((s) => s.name)).size !== 15)
  throw Error("Unexpected text ABI");
const digest = createHash("sha256")
  .update("TEXT01-v1\n" + signatures.map((s) => s.rust).join("\n"))
  .digest();
const fingerprint = Array.from({ length: 8 }, (_, i) => digest.readUInt32LE(i * 4));
const content = `// Generated by scripts/text-boundary.ts.\nexport type TextCore = {\n  memory: WebAssembly.Memory;\n${signatures.map((s) => `  ${s.name}(${s.args.join(", ")}): ${s.result};`).join("\n")}\n};\nexport const textArity = ${JSON.stringify(Object.fromEntries(signatures.map((s) => [s.name, s.args.length])))} as const;\nexport const textFingerprint = ${JSON.stringify(fingerprint)} as const;\n`;
const formatted = execFileSync(
  process.execPath,
  [root + "node_modules/oxfmt/bin/oxfmt", "--stdin-filepath", "text-core.ts"],
  { input: content, encoding: "utf8" },
);
for (const [path, text] of [
  ["apps/vector-editor/src/text-core.ts", formatted],
  [
    "apps/vector-editor/src/saving/text-boundary-generated.js",
    `// Generated by scripts/text-boundary.ts.\nconst textStorageArity = ${JSON.stringify(Object.fromEntries(signatures.map((s) => [s.name, s.args.length])))};\nconst textStorageFingerprint = ${JSON.stringify(fingerprint)};\n`,
  ],
  [
    "crates/vector-engine/src/text_generated.rs",
    `// Generated by scripts/text-boundary.ts.\npub const TEXT_FINGERPRINT: [u32; 8] = [${fingerprint.join(", ")}];\n`,
  ],
]) {
  if (!path || !text) throw Error("Missing export output");
  if (process.argv.includes("--check")) {
    if (readFileSync(root + path, "utf8") !== text) throw Error("Stale text boundary");
  } else writeFileSync(root + path, text);
}
console.log(`Checked ${signatures.length} text exports`);
