import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// This deliberately accepts only the donor's scalar C ABI. New compound types
// must receive an explicit adapter rather than silently becoming JS numbers.
const root = fileURLToPath(new URL("../", import.meta.url));
const sources = [
  "lib",
  "layers",
  "selection",
  "slice",
  "camera",
  "regional",
  "geometry_wide_transport",
  "geometry_wide_snapshot",
];
const rustSignatures: string[] = [];
const signatures: { name: string; args: string[]; result: string }[] = [];
function scalar(type: string): string {
  if (type.trim() === "i64") return "bigint";
  if (/^(?:u32|usize|f32|f64|\*(?:const|mut) (?:f32|f64|u8))$/.test(type.trim())) return "number";
  throw Error(`Unsupported vector ABI type: ${type}`);
}
for (const source of sources) {
  const text = readFileSync(`${root}crates/vector-engine/src/${source}.rs`, "utf8");
  for (const match of text.matchAll(
    /pub extern "C" fn (\w+)\s*\(([^)]*)\)\s*(?:->\s*([^{]+))?\s*\{/g,
  )) {
    const functionName = match[1],
      parameters = match[2],
      returnType = match[3];
    if (!functionName || parameters === undefined) throw Error("Malformed vector ABI signature");
    rustSignatures.push(
      `${functionName}(${parameters.replace(/\s+/g, "")})->${(returnType || "()").replace(/\s+/g, "")}`,
    );
    const args = parameters
      .split(",")
      .map((part) => part.trim())
      .filter(Boolean)
      .map((part) => {
        const [name, type] = part.split(":");
        if (!name || !type) throw Error(`Malformed vector ABI argument: ${part}`);
        return `${name.trim()}: ${scalar(type)}`;
      });
    signatures.push({ name: functionName, args, result: returnType ? scalar(returnType) : "void" });
  }
}
signatures.sort((a, b) => a.name.localeCompare(b.name));
if (new Set(signatures.map((entry) => entry.name)).size !== signatures.length)
  throw Error("Duplicate vector ABI export");
const digest = createHash("sha256").update(rustSignatures.sort().join("\n")).digest();
const fingerprint = Array.from({ length: 8 }, (_, index) => digest.readUInt32LE(index * 4));
const rustGenerated = `// Generated by scripts/vector-editor-boundary.ts. Do not edit.\npub const ABI_FINGERPRINT: [u32; 8] = [${fingerprint.join(", ")}];\n`;
const rustPath = `${root}crates/vector-engine/src/boundary_generated.rs`;
const generated = `// Generated by scripts/vector-editor-boundary.ts. Do not edit.\nexport type Core = {\n${signatures.map(({ name, args, result }) => `  ${name}(${args.join(", ")}): ${result};`).join("\n")}\n  memory: WebAssembly.Memory;\n};\n\nexport const coreExportArity = ${JSON.stringify(Object.fromEntries(signatures.map(({ name, args }) => [name, args.length])), null, 2)} as const;\n`;
const output =
  generated + `\nexport const coreAbiFingerprint = ${JSON.stringify(fingerprint)} as const;\n`;
const path = `${root}apps/vector-editor/src/core.ts`;
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output || readFileSync(rustPath, "utf8") !== rustGenerated)
    throw Error("Generated vector ABI is stale");
} else {
  writeFileSync(path, output);
  writeFileSync(rustPath, rustGenerated);
}
console.log(`Checked ${signatures.length} Rust-owned vector ABI functions`);
