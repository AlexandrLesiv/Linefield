import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// This deliberately accepts only the donor's scalar C ABI. New compound types
// must receive an explicit adapter rather than silently becoming JS numbers.
const root = fileURLToPath(new URL("../", import.meta.url));
const sources = ["lib", "layers", "selection", "slice"];
const signatures: { name: string; args: string[]; result: string }[] = [];
function scalar(type: string): string {
  if (/^(?:u32|usize|f32|f64|\*(?:const|mut) (?:f32|u8))$/.test(type.trim())) return "number";
  throw Error(`Unsupported vector ABI type: ${type}`);
}
for (const source of sources) {
  const text = readFileSync(`${root}apps/vector-editor/core/src/${source}.rs`, "utf8");
  for (const match of text.matchAll(
    /pub extern "C" fn (\w+)\s*\(([^)]*)\)\s*(?:->\s*([^{]+))?\s*\{/g,
  )) {
    const args = match[2]
      .split(",")
      .map((part) => part.trim())
      .filter(Boolean)
      .map((part) => {
        const [name, type] = part.split(":");
        return `${name.trim()}: ${scalar(type)}`;
      });
    signatures.push({ name: match[1], args, result: match[3] ? scalar(match[3]) : "void" });
  }
}
signatures.sort((a, b) => a.name.localeCompare(b.name));
if (new Set(signatures.map((entry) => entry.name)).size !== signatures.length)
  throw Error("Duplicate vector ABI export");
const generated = `// Generated by scripts/vector-editor-boundary.ts. Do not edit.\nexport type Core = {\n${signatures.map(({ name, args, result }) => `  ${name}(${args.join(", ")}): ${result};`).join("\n")}\n  memory: WebAssembly.Memory;\n};\n\nexport const coreExportArity = ${JSON.stringify(Object.fromEntries(signatures.map(({ name, args }) => [name, args.length])), null, 2)} as const;\n`;
const path = `${root}apps/vector-editor/src/core.ts`;
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== generated) throw Error("Generated vector ABI is stale");
} else writeFileSync(path, generated);
console.log(`Checked ${signatures.length} Rust-owned vector ABI functions`);
