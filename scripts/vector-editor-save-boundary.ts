import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const sources = [
  "save_delta_transport",
  "save_idle",
  "save_idle_stream",
  "save_idle_retire",
  "save_replay",
  "save_authority",
  "save_seal",
  "save_settings",
];
const signatures: { name: string; args: string[]; result: string; rust: string }[] = [];
function scalar(type: string): string {
  if (/^(?:i64|u64)$/.test(type.trim())) return "bigint";
  if (/^(?:u32|usize|\*(?:const|mut) u8)$/.test(type.trim())) return "number";
  throw Error(`Unsupported save boundary type: ${type}`);
}
for (const source of sources) {
  const text = readFileSync(`${root}crates/vector-engine/src/${source}.rs`, "utf8");
  for (const match of text.matchAll(
    /pub extern "C" fn (\w+)\s*\(([^)]*)\)\s*(?:->\s*([^{]+))?\s*\{/g,
  )) {
    const [, name, parameters, result] = match;
    if (!name || parameters === undefined) throw Error("Malformed save signature");
    const args = parameters
      .split(",")
      .map((p) => p.trim())
      .filter(Boolean)
      .map((p) => {
        const [arg, type] = p.split(":");
        if (!arg || !type) throw Error("Malformed save argument");
        return `${arg.trim()}: ${scalar(type)}`;
      });
    signatures.push({
      name,
      args,
      result: result ? scalar(result) : "void",
      rust: `${name}(${parameters.replace(/\s+/g, "")})->${(result || "()").replace(/\s+/g, "")}`,
    });
  }
}
signatures.sort((a, b) => a.name.localeCompare(b.name));
if (new Set(signatures.map((s) => s.name)).size !== signatures.length)
  throw Error("Duplicate save export");
const digest = createHash("sha256")
  .update(
    signatures
      .map((s) => s.rust)
      .sort()
      .join("\n"),
  )
  .digest();
const fingerprint = Array.from({ length: 8 }, (_, i) => digest.readUInt32LE(i * 4));
const rust = `// Generated by scripts/vector-editor-save-boundary.ts. Do not edit.\npub const SAVE_FINGERPRINT: [u32; 8] = [${fingerprint.join(", ")}];\n`;
const types = `// Generated by scripts/vector-editor-save-boundary.ts. Do not edit.\nexport type SaveCore = {\n${signatures.map((s) => `  ${s.name}(${s.args.join(", ")}): ${s.result};`).join("\n")}\n  memory: WebAssembly.Memory;\n};\nexport const saveArity = ${JSON.stringify(Object.fromEntries(signatures.map((s) => [s.name, s.args.length])), null, 2)} as const;\nexport const saveFingerprint = ${JSON.stringify(fingerprint)} as const;\n`;
const formattedTypes = execFileSync(
  process.execPath,
  [root + "node_modules/oxfmt/bin/oxfmt", "--stdin-filepath", "boundary.ts"],
  { input: types, encoding: "utf8" },
);
for (const [path, content] of [
  ["crates/vector-engine/src/save_boundary_generated.rs", rust],
  ["apps/vector-editor/src/saving/boundary.ts", formattedTypes],
]) {
  if (!path || !content) throw Error("Missing generated output");
  if (process.argv.includes("--check")) {
    if (readFileSync(root + path, "utf8") !== content) throw Error("Save boundary is stale");
  } else writeFileSync(root + path, content);
}
console.log(`Checked ${signatures.length} Rust-owned save functions`);
