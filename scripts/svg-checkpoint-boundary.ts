import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const signatures: string[] = [];
function scalar(type: string): string {
  if (/^(u64|i64)$/.test(type.trim())) return "bigint";
  if (/^(u32|usize|f64|\*const f64)$/.test(type.trim())) return "number";
  throw Error(`Unsupported checkpoint scalar: ${type}`);
}
for (const file of ["mod", "boundary", "stream", "retire"]) {
  const source = readFileSync(`${root}crates/vector-engine/src/svg_checkpoint/${file}.rs`, "utf8");
  for (const match of source.matchAll(/pub extern "C" fn (\w+)\(([^)]*)\)\s*->\s*([^{]+)\{/g)) {
    const args = match[2]!
      .split(",")
      .map((arg) => arg.trim())
      .filter(Boolean)
      .map((arg) => {
        const [name, type] = arg.split(":");
        return `${name!.trim()}: ${scalar(type!)}`;
      });
    signatures.push(`  ${match[1]}(${args.join(", ")}): ${scalar(match[3]!)};`);
  }
}
if (signatures.length !== 12) throw Error(`Unexpected SVG checkpoint ABI: ${signatures.length}`);
const content = `// Generated by scripts/svg-checkpoint-boundary.ts; isolated checkpoint only.\nexport type SvgCheckpoint = {\n  memory: WebAssembly.Memory;\n${signatures.sort().join("\n")}\n};\n`;
const path = `${root}scripts/svg-checkpoint-types.ts`;
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== content) throw Error("Stale SVG checkpoint boundary");
} else writeFileSync(path, content);
console.log(`Checked ${signatures.length} isolated SVG checkpoint exports`);
